// Coverage of the swarm genome by tests on real LLM agents. Generated from catalog/genome/traits.json, research/FLAGS.md,
// catalog/genome/evidence.json, results/li-verdicts.json and results/sims/screen-noflag.json; writes catalog/genome/COVERAGE.md.
// Usage: node scripts/coverage.mjs          write
//        node scripts/coverage.mjs --check  fail if the committed table is stale or evidence.json names an unknown trait or hypothesis
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const rd = (p) => readFileSync(join(ROOT, p), 'utf8');
const traits = JSON.parse(rd('catalog/genome/traits.json'));
const evidence = JSON.parse(rd('catalog/genome/evidence.json'));
const verdicts = JSON.parse(rd('results/li-verdicts.json'));
const screen = existsSync(join(ROOT, 'results/sims/screen-noflag.json')) ? JSON.parse(rd('results/sims/screen-noflag.json')) : null;

// flag -> status, from the FLAGS.md tables (first backticked word of the last column)
const flagStatus = {};
for (const line of rd('research/FLAGS.md').split('\n')) {
  if (!line.startsWith('| `')) continue;
  const cols = line.split('|').map((c) => c.trim()).filter(Boolean);
  const st = (cols[cols.length - 1].match(/`([a-z-]+)`/) || [])[1];
  if (!st) continue;
  for (const f of cols[0].matchAll(/`([a-z_]+)`/g)) flagStatus[f[1]] = st;
}

const problems = [];
const vById = Object.fromEntries(verdicts.hypotheses.map((h) => [h.id, h.registered]));
const traitIds = new Set(traits.traits.map((t) => t.id));
for (const [tid, e] of Object.entries(evidence.traits)) {
  if (!traitIds.has(tid)) problems.push(`evidence.json: unknown trait ${tid}`);
  for (const h of e.hypotheses) if (!vById[h]) problems.push(`evidence.json: ${tid} names unknown hypothesis ${h}`);
}
for (const t of traits.traits) for (const f of t.flags) if (!flagStatus[f]) problems.push(`FLAGS.md: no status for flag ${f} (trait ${t.id})`);

const LLM_TESTED = new Set(['positive-eng', 'null-llm']);
const rows = traits.traits.map((t) => {
  const ev = evidence.traits[t.id];
  const hs = ev ? ev.hypotheses.map((h) => ({ id: h, v: vById[h] })) : [];
  const n = (v) => hs.filter((h) => h.v === v).length;
  const fs = t.flags.map((f) => flagStatus[f]);
  const flagTested = fs.some((s) => LLM_TESTED.has(s));
  const tested = hs.length > 0 || flagTested;
  const l1 = n('supported') > 0;
  const dec = screen && screen.decisions.find((d) => d.trait === t.id);
  const level = l1 ? 'L1' : dec && dec.advance ? 'L0' : '-';
  const state = l1 ? 'L1 on real agents' : hs.length ? 'tested, no supported hypothesis' : flagTested ? 'tested at flag level' : fs.includes('sim-support') ? 'simulation only' : t.flags.length ? 'untested' : dec ? (dec.advance ? 'screened: advance' : 'screened: stop') : 'no flag';
  return { id: t.id, axis: t.axis, name: t.name, flags: t.flags, fs, hs, tested, l1, level, state, sup: n('supported'), ref: n('refuted'), inc: n('inconclusive') + n('aborted') + n('pending') };
});

const out = [];
out.push('# Coverage of the swarm genome on real LLM agents', '');
out.push('Generated by `node scripts/coverage.mjs` from `catalog/genome/traits.json` (39 traits, 7 axes), the flag statuses in `research/FLAGS.md`, the curated map `catalog/genome/evidence.json` and the verdicts in `results/li-verdicts.json`. Do not edit by hand; CI fails when it is stale.', '');
out.push('Levels follow the evidence ladder in `programs/coordination.md`. **L1** here means at least one preregistered hypothesis about the trait is `supported` on real agents (the map lists the hypotheses). **L0** means a free simulation screen says the trait is worth a paid study. A flag-level test (`positive-eng`, `null-llm` in `research/FLAGS.md`) is shown as tested but earns no level, because those runs predate the preregistered LI studies. L2 and beyond (three models, a strong manager, real code, ablation) are not tracked yet: no trait has them.', '');
out.push('## By axis', '', '| Axis | Traits | With a flag | Tested on real agents | L1 | L0 (screen) |', '|---|---|---|---|---|---|');
for (const a of traits.axes) {
  const r = rows.filter((x) => x.axis === a.id);
  out.push(`| ${a.id} ${a.name} | ${r.length} | ${r.filter((x) => x.flags.length).length} | ${r.filter((x) => x.tested).length} | ${r.filter((x) => x.l1).length} | ${r.filter((x) => x.level === 'L0').length} |`);
}
out.push(`| **All** | **${rows.length}** | **${rows.filter((x) => x.flags.length).length}** | **${rows.filter((x) => x.tested).length}** | **${rows.filter((x) => x.l1).length}** | **${rows.filter((x) => x.level === 'L0').length}** |`, '');
out.push('## By trait', '', '| Trait | Name | Flags (status) | LI hypotheses on real agents | State | Level |', '|---|---|---|---|---|---|');
for (const x of rows) {
  const fl = x.flags.length ? x.flags.map((f, i) => `\`${f}\` (${x.fs[i]})`).join(', ') : '-';
  const hy = x.hs.length ? `${x.hs.map((h) => h.id).join(', ')}: ${x.sup} supported, ${x.ref} refuted, ${x.inc} inconclusive or pending` : '-';
  out.push(`| ${x.id} | ${x.name} | ${fl} | ${hy} | ${x.state} | ${x.level} |`);
}
out.push('', 'Traits with no flag are screened in `results/sims/screen-noflag.md`.', '');
const text = out.join('\n');
const path = join(ROOT, 'catalog/genome/COVERAGE.md');
if (process.argv.includes('--check')) {
  const same = existsSync(path) && readFileSync(path, 'utf8') === text;
  if (!same) problems.push('catalog/genome/COVERAGE.md is stale: run node scripts/coverage.mjs');
  for (const p of problems) console.log('coverage: ' + p);
  console.log(problems.length ? 'coverage: FAIL' : 'coverage: ok');
  process.exit(problems.length ? 1 : 0);
}
for (const p of problems) console.log('warning: ' + p);
writeFileSync(path, text);
console.log(`coverage: ${rows.length} traits, ${rows.filter((x) => x.tested).length} tested, ${rows.filter((x) => x.l1).length} at L1, ${rows.filter((x) => x.level === 'L0').length} at L0`);
